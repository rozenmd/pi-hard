type ProbeObservation = {
  value: {
    status: number;
    contentType: string;
    requestId: string | null;
    rayId: string | null;
  } | null;
};

export const AnthropicSetup = Schema.Struct({
  token: Schema.String.check(Schema.isMaxLength(8192)),
});

export const AnthropicProbe = Schema.Struct({ model: Schema.optional(AnthropicModel) });

/** Eager HTTP adapter: never load the Node-only interactive OAuth flow or run a CLI in the Worker. */
export function claudeProvider(onHeaders?: (headers: Record<string, string>) => void) {
  const provider = anthropicProvider();

  return createProvider({
    id: provider.id,
    name: provider.name,
    baseUrl: provider.baseUrl,
    models: provider.getModels(),
    auth: { apiKey: provider.auth.apiKey },
    api: onHeaders
      ? {
          stream: observeUsage(stream, onHeaders),
          streamSimple: observeUsage(streamSimple, onHeaders),
        }
      : { stream, streamSimple },
  });
}

export const anthropicStatus = (credentials: Credentials) =>
  credentials
    .get("anthropic")
    .pipe(Effect.map((credential) => ({ connected: Option.isSome(credential) })));

export const saveAnthropic = (credentials: Credentials, input: typeof AnthropicSetup.Type) =>
  credentials.locked(
    Effect.gen(function* () {
      // Open Session likewise removes line-wrapping whitespace from `claude setup-token` output.
      const token = input.token.replace(/\s+/g, "");

      if (!/^sk-ant-oat01-[A-Za-z0-9_-]{20,}$/.test(token))
        return {
          error:
            "Paste a Claude subscription token generated by claude setup-token, not an API key.",
        };
      yield* credentials.put("anthropic", { type: "api_key", key: token });

      return { connected: true };
    }),
  );

/** Explicit, bounded, real inference probe. No retries, refresh, tool execution or conversation side effects. */
export const testAnthropic = (credentials: Credentials, input: typeof AnthropicProbe.Type) =>
  Effect.gen(function* () {
    const credential = Option.getOrUndefined(yield* credentials.get("anthropic"));

    if (credential?.type !== "api_key" || !credential.key) return { error: "Connect Claude first" };
    const token = credential.key;
    const models = createModels({ credentials });
    const provider = claudeProvider();
    models.setProvider(provider);

    const model = provider
      .getModels()
      .find((candidate) => candidate.id === (input.model ?? "claude-haiku-5-5"));

    if (!model) return { error: "Unknown Claude model" };
    const upstream: ProbeObservation = { value: null };
    const started = Date.now();

    const response = yield* attempt("anthropic.probe", (signal) =>
      models.completeSimple(
        model,
        {
          messages: [{ role: "user", content: "Reply with OK.", timestamp: Date.now() }],
        },
        {
          signal: AbortSignal.any([signal, AbortSignal.timeout(30_000)]),
          maxTokens: 32,
          maxRetries: 0,
          fetch: async (url, init) => {
            const response = await fetch(url, { ...init, redirect: "manual" });

            const header = (name: string) => {
              const value = response.headers.get(name);

              return value === null ? null : redact(value, [token]).slice(0, 256);
            };

            upstream.value = {
              status: response.status,
              contentType: header("content-type") ?? "",
              requestId: header("request-id"),
              rayId: header("cf-ray"),
            };

            return response;
          },
        },
      ),
    ).pipe(
      Effect.map((message) => ({ message })),
      Effect.catchTag("OperationError", (error) =>
        Effect.succeed({ error: redact(error.message, [token]) }),
      ),
    );

    const ok =
      "message" in response &&
      response.message.stopReason !== "error" &&
      response.message.stopReason !== "aborted" &&
      response.message.content.some((block) => block.type === "text" && block.text.trim());

    const error = "error" in response ? response.error : response.message.errorMessage;
    const diagnostic = upstream.value;

    return {
      ok,
      model: model.id,
      durationMs: Date.now() - started,
      upstream: diagnostic,
      message: ok
        ? "Claude returned a live inference response from this Worker."
        : diagnostic?.contentType.includes("text/html")
          ? `Anthropic returned HTTP ${diagnostic.status} HTML instead of a model response. This may be an upstream edge block.`
          : redact(error ?? "No text response was returned", [token]).slice(0, 1024),
    };
  });
